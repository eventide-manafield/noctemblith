async function setComments(queryRunner, restore) {
	const schema = queryRunner.connection.options.schema
		?? (await queryRunner.query('SELECT current_schema() AS schema'))[0]?.schema;
	if (!/^[a-z_][a-z0-9_]{0,62}$/.test(schema)) {
		throw new Error('Noctemblith DB schema must be a valid lowercase PostgreSQL identifier');
	}
	for (const [table, column, comment] of comments) {
		const value = restore ? "'" + comment.replaceAll("'", "''") + "'" : 'NULL';
		await queryRunner.query(`COMMENT ON COLUMN "${schema}"."${table}"."${column}" IS ${value}`);
	}
}

